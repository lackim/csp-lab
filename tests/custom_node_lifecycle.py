"""Real Docker proof of custom image contract, restart identity, and isolation."""

import json
import secrets
import subprocess

from csp_lab import Lab, Node


def docker(*args: str) -> str:
    return subprocess.run(
        ["docker", *args], capture_output=True, text=True, check=True, timeout=600
    ).stdout.strip()


def containers(project: str) -> str:
    return docker("ps", "-aq", "--filter", f"label=com.docker.compose.project={project}")


def main() -> None:
    tag = f"csp-lab-uppercase:test-{secrets.token_hex(8)}"
    try:
        docker("build", "-f", "examples/custom-node/Dockerfile", "-t", tag, ".")
        original = docker("image", "inspect", "--format", "{{.Id}}", tag)
        config = json.loads(docker("image", "inspect", "--format", "{{json .Config}}", tag))
        with Lab(protocol=2, build=True) as unrelated:
            for protocol in (1, 2):
                lab = Lab(protocol=protocol, build=True, nodes=(Node(5, tag),))
                with lab:
                    assert lab.ping(5).reachable
                    assert lab.topology().nodes == [2, 3, 5]
                    report = lab.diagnose()
                    assert report.healthy and report.image_ids == {5: original}
                    container = docker(
                        "ps",
                        "-aq",
                        "--filter",
                        f"label=com.docker.compose.project={lab.project}",
                        "--filter",
                        "label=com.docker.compose.service=custom5",
                    )
                    inspected = json.loads(docker("container", "inspect", container))[0]
                    assert inspected["Image"] == original
                    for key in ("Entrypoint", "Cmd", "User"):
                        assert inspected["Config"][key] == config[key]
                    assert inspected["Config"]["User"] == "10001"
                    assert f"CSP_LAB_PROTOCOL={protocol}" in inspected["Config"]["Env"]
                    assert "CSP_LAB_ADDRESS=5" in inspected["Config"]["Env"]
                    assert (
                        "CSP_LAB_ZMQ_PUBLISH_ENDPOINT=tcp://hub:6000" in inspected["Config"]["Env"]
                    )
                    assert (
                        "CSP_LAB_ZMQ_SUBSCRIBE_ENDPOINT=tcp://hub:7000"
                        in inspected["Config"]["Env"]
                    )
                    assert not inspected["Mounts"]
                    assert not inspected["HostConfig"]["Privileged"]
                    assert not inspected["HostConfig"]["PortBindings"]

                    # A retagged incompatible executable cannot replace the
                    # original container when the caller asks for restart.
                    docker("image", "tag", lab.image, tag)
                    lab.stop_node(5)
                    lab.stop_node(5)
                    assert not lab.ping(5).reachable
                    assert lab.topology().nodes == [2, 3, 5]
                    assert lab.ping(2).reachable and unrelated.ping(3).reachable
                    lab.start_node(5)
                    lab.start_node(5)
                    assert lab.diagnose().healthy
                    assert (
                        docker("container", "inspect", "--format", "{{.Image}}", container)
                        == original
                    )
                    docker("image", "tag", original, tag)
                assert containers(lab.project) == ""
                assert docker("image", "inspect", "--format", "{{.Id}}", tag) == original
                assert unrelated.ping(2).reachable
        assert containers(unrelated.project) == ""
        print(
            "Custom node lifecycle passed: CSP v1/v2, image contract, restart identity, isolation"
        )
    finally:
        # This tag was generated by this test. Lab itself must never remove it.
        subprocess.run(
            ["docker", "image", "rm", tag], check=False, capture_output=True, timeout=120
        )


if __name__ == "__main__":
    main()
